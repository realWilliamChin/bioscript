export PATH=$JAVA_HOME/bin:$PATH'

alias java11='export JAVA_HOME=/home/data/opt/syssoft/openjdk-11.0.29; \
export PATH=$JAVA_HOME/bin:$PATH'

alias java21='export JAVA_HOME=/home/data/opt/syssoft/openjdk-21.0.9; \
